// signForScheme signs enc (the base64 STRING, matching the section's
// shared gotcha) with a freshly generated scheme-appropriate keypair,
// returning the crypto.PublicKey value ready to pass to
// (*MachineFile).Verify, plus the raw signature bytes.
func signForScheme(t *testing.T, scheme LicenseScheme, enc string) (any, []byte) {
	t.Helper()
	switch scheme {
	case SchemeEd25519Sign:
		pub, priv, err := ed25519.GenerateKey(nil)
		if err != nil {
			t.Fatalf("ed25519.GenerateKey() error = %v", err)
		}
		return pub, ed25519.Sign(priv, []byte(enc))
	case SchemeRSA2048PKCS1Sign:
		priv, err := rsa.GenerateKey(rand.Reader, 2048)
		if err != nil {
			t.Fatalf("rsa.GenerateKey() error = %v", err)
		}
		digest := sha256.Sum256([]byte(enc))
		sig, err := rsa.SignPKCS1v15(rand.Reader, priv, crypto.SHA256, digest[:])
		if err != nil {
			t.Fatalf("rsa.SignPKCS1v15() error = %v", err)
		}
		return &priv.PublicKey, sig
	case SchemeRSA2048PKCS1PSSSign:
		priv, err := rsa.GenerateKey(rand.Reader, 2048)
		if err != nil {
			t.Fatalf("rsa.GenerateKey() error = %v", err)
		}
		digest := sha256.Sum256([]byte(enc))
		sig, err := rsa.SignPSS(rand.Reader, priv, crypto.SHA256, digest[:], nil)
		if err != nil {
			t.Fatalf("rsa.SignPSS() error = %v", err)
		}
		return &priv.PublicKey, sig
	case SchemeECDSAP256Sign:
		priv, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
		if err != nil {
			t.Fatalf("ecdsa.GenerateKey() error = %v", err)
		}
		digest := sha256.Sum256([]byte(enc))
		sig, err := ecdsa.SignASN1(rand.Reader, priv, digest[:])
		if err != nil {
			t.Fatalf("ecdsa.SignASN1() error = %v", err)
		}
		return &priv.PublicKey, sig
	default:
		t.Fatalf("signForScheme: unsupported scheme %v", scheme)
		return nil, nil
	}
}

func schemeAlgSuffixForTest(t *testing.T, scheme LicenseScheme) string {
	t.Helper()
	suffix, err := schemeAlgSuffix(scheme)
	if err != nil {
		t.Fatalf("schemeAlgSuffix() error = %v", err)
	}
	return suffix
}

// buildSelfGeneratedMachinePEM builds a .machine PEM from this SDK's own
// understanding of the wire format.
//
// ⚠️ USE THIS ONLY FOR CASES THE SERVER CANNOT PRODUCE, and only to assert
// that Verify REJECTS something. Never to assert that a file verifies.
//
// A self-generated fixture proves nothing about format conformance: it
// reproduces whatever the verifier believes, so a verifier and a fixture that
// share a misreading agree with each other forever while no file the server
// actually emits can be opened. That is exactly how the M1/M2/M3 defects
// survived. Real conformance is asserted in machine_file_v2_test.go against
// certificates produced by the server's own encode_machine_file.
//
// payloadJSON is signed as-is so a caller can hand in a payload the server
// would never emit — e.g. one with no meta claims.
func buildSelfGeneratedMachinePEM(t *testing.T, scheme LicenseScheme, payloadJSON string) (any /* pub */, string /* pem */) {
	t.Helper()
	enc := base64.StdEncoding.EncodeToString([]byte(payloadJSON))
	pub, sig := signForScheme(t, scheme, enc)
	cert := certPayload{
		Enc: enc,
		Sig: base64.StdEncoding.EncodeToString(sig),
		Alg: "base64+" + schemeAlgSuffixForTest(t, scheme) + "+" + machineFileAlgV2Marker,
	}
	certJSON, err := json.Marshal(cert)
	if err != nil {
		t.Fatalf("json.Marshal() error = %v", err)
	}
	pemBody := base64.StdEncoding.EncodeToString(certJSON)
	return pub, machineFilePEMHeader + "\n" + pemBody + "\n" + machineFilePEMFooter
}

