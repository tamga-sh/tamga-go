// TestMachineFileVerify_RejectsPreV2SelfGeneratedFixtures retires this repo's
// four original testdata/machine_file_*.machine certificates by turning them
// into what they actually are.
//
// They were generated by this SDK from its own reading of the format, and they
// carry a pre-v2 alg ("base64+ed25519", "aes-256-gcm+ecdsa-p256") with no
// signed meta claims — the shape a v1 server produced, which also derived its
// AES key by zero-padding the license key instead of through HKDF. They were
// the only thing standing behind "machine file verification works" here, and
// they passed because the verifier shared their misreading. Renamed to
// testdata/pre_v2_selfgenerated_*.machine, they are now negative fixtures for
// the rule that a file without +v2 must be refused.
//
// Each is verified against a freshly generated public key that could not
// possibly have signed it: the alg gate has to reject it anyway, and any
// ErrInvalidSignature here would mean the gate ran after the crypto instead
// of before it.
// readTestdataFixture reads a fixture from testdata/ by base name.
//
// The path is assembled here rather than at each call site so gosec's G304
// (file inclusion via variable) has a single place to look at: name comes
// from a literal table inside a test, never from input, and testdata/ is the
// only directory reachable.
func readTestdataFixture(t *testing.T, name string) ([]byte, error) {
	t.Helper()
	return os.ReadFile(filepath.Join("testdata", filepath.Base(name)))
}

func TestMachineFileVerify_RejectsPreV2SelfGeneratedFixtures(t *testing.T) {
	fixtures := map[string]LicenseScheme{
		"pre_v2_selfgenerated_ed25519.machine":   SchemeEd25519Sign,
		"pre_v2_selfgenerated_ecdsa.machine":     SchemeECDSAP256Sign,
		"pre_v2_selfgenerated_rsa_pkcs1.machine": SchemeRSA2048PKCS1Sign,
		"pre_v2_selfgenerated_rsa_pss.machine":   SchemeRSA2048PKCS1PSSSign,
	}
	for name, scheme := range fixtures {
		t.Run(name, func(t *testing.T) {
			pemBytes, err := readTestdataFixture(t, name)
			if err != nil {
				t.Fatalf("ReadFile() error = %v", err)
			}
			file, err := ParseMachineFile(string(pemBytes))
			if err != nil {
				t.Fatalf("ParseMachineFile() error = %v", err)
			}
			if strings.HasSuffix(file.Alg, "+"+machineFileAlgV2Marker) {
				t.Fatalf("fixture %s is not pre-v2 (alg = %q); it no longer tests what it claims to", name, file.Alg)
			}

			unrelatedPub, _ := signForScheme(t, scheme, "unrelated")
			_, err = file.Verify(scheme, unrelatedPub, "lic-abc123", "fp-abc123")
			if err == nil {
				t.Fatalf("Verify() accepted a pre-v2 file (alg = %q)", file.Alg)
			}
			if errors.Is(err, ErrInvalidSignature) {
				t.Errorf("pre-v2 file rejected as ErrInvalidSignature; the alg gate must run before signature verification (err = %v)", err)
			}
		})
	}
}

// TestMachineFileVerify_RejectsPayloadWithNoSignedClaims covers the one case
// the server cannot produce, so it needs a self-generated file:
// check_out_machine.rs always builds meta, so a correctly-signed v2 file whose
// payload has none is not what its own +v2 marker claims — and admitting it
// would mean an offline file with no exp to enforce.
func TestMachineFileVerify_RejectsPayloadWithNoSignedClaims(t *testing.T) {
	pub, pem := buildSelfGeneratedMachinePEM(t, SchemeEd25519Sign, representativeMachinePayloadJSON())
	file, err := ParseMachineFile(pem)
	if err != nil {
		t.Fatalf("ParseMachineFile() error = %v", err)
	}
	_, err = file.Verify(SchemeEd25519Sign, pub, "", "")
	if !errors.Is(err, ErrMissingClaims) {
		t.Fatalf("err = %v, want ErrMissingClaims", err)
	}
}

func TestCheckTTL_BoundaryValues(t *testing.T) {
	tests := []struct {
		name    string
		ttl     int
		wantErr bool
	}{
		{"zero", 0, true},
		{"one", 1, false},
		{"max", maxCheckoutTTLSeconds, false},
		{"max_plus_one", maxCheckoutTTLSeconds + 1, true},
		{"negative", -1, true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := checkTTL(tt.ttl)
			if (err != nil) != tt.wantErr {
				t.Errorf("checkTTL(%d) error = %v, wantErr %v", tt.ttl, err, tt.wantErr)
			}
			if err != nil && !errors.Is(err, ErrTTLInvalid) {
				t.Errorf("checkTTL(%d) error = %v, want it to match ErrTTLInvalid", tt.ttl, err)
			}
		})
	}
}

func TestCheckOutMachine_RejectsInvalidTTLBeforeRequest(t *testing.T) {
	var serverCalled bool
	c, closeFn := newTestClient(t, func(w http.ResponseWriter, r *http.Request) {
		serverCalled = true
		w.WriteHeader(http.StatusOK)
	})
	defer closeFn()

	badTTL := 0
	_, err := c.CheckOutMachine(context.Background(), "mach-id", CheckOutOptions{TTL: &badTTL})
	if !errors.Is(err, ErrTTLInvalid) {
		t.Fatalf("err = %v, want ErrTTLInvalid", err)
	}
	if serverCalled {
		t.Fatal("server was called despite an invalid TTL — must short-circuit client-side")
	}
}

